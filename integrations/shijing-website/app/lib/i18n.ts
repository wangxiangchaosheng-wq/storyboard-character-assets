export const MESSAGES: Record<Locale, Record<string, string>> = { 'zh-CN': ZH, en: EN };

const isLocale = (value: unknown): value is Locale => LOCALES.includes(value as Locale);

/** 开发期才 warn：生产环境静默返回 key，不让控制台成为漏翻的报警器。 */
const isDev = (): boolean => typeof process === 'undefined' || !process.env || process.env.NODE_ENV !== 'production';

/**
 * 探测语言：本机选择 → 浏览器语言 → 兜底。
 * 无 localStorage（SSR、隐私模式）时不抛，直接落到下一级信号。
 * 非中文浏览器记 en：游戏出海后英语是默认国际语言，中文浏览器才值得显式切中文。
 */
export function detectLocale(): Locale {
  try {
    const saved = localStorage.getItem(LOCALE_KEY);
    if (isLocale(saved)) return saved;
  } catch { /* 存储不可用：继续看浏览器语言 */ }
  try {
    const language = navigator?.language || '';
    if (language.toLowerCase().startsWith('zh')) return 'zh-CN';
    if (language) return 'en';
  } catch { /* 无 navigator（SSR） */ }
  return DEFAULT_LOCALE;
}

/** <html lang> 跟随界面语言：屏幕阅读器与字体回退都靠它。 */
const applyLocaleToDocument = (locale: Locale): void => {
  try { document.documentElement.lang = locale; } catch { /* SSR 无 document */ }
};

/** 写本机选择 + 同步 <html lang> + 通知同页面其它 useLocale 实例。 */
export function setLocale(locale: Locale): void {
  if (!isLocale(locale)) return;
  try { localStorage.setItem(LOCALE_KEY, locale); } catch { /* 存储不可用只影响下次默认值 */ }
  applyLocaleToDocument(locale);
  try { dispatchEvent(new Event(LOCALE_EVENT)); } catch { /* SSR 无事件 */ }
}

/** 供根布局的 client 包装组件调用（见 components/LocaleLangSync.tsx）。 */
export const syncLocaleToDocument = applyLocaleToDocument;

const interpolate = (template: string, vars?: Record<string, string | number>): string => {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
};

/** 取文案；支持 {name} 插值。缺 key 返回 key 本身（开发期 console.warn）。 */
export function translate(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const table = MESSAGES[locale] ?? MESSAGES[DEFAULT_LOCALE];
  const hit = table[key] ?? MESSAGES[DEFAULT_LOCALE][key];
  if (hit === undefined) {
    if (isDev()) console.warn(`[i18n] missing key "${key}" for locale ${locale}`);
    return key;
  }
  return interpolate(hit, vars);
}

/**
 * 枚举值 → 文案：把引擎枚举（fog 档位、外交立场、计策类型、失败模式、治政模式…）
 * 加上前缀查表。值不在表内时回落原值且不 warn——引擎将来新增枚举不该污染控制台。
 */
export function translateEnum(locale: Locale, prefix: string, value: string): string {
  const table = MESSAGES[locale] ?? MESSAGES[DEFAULT_LOCALE];
  return table[`${prefix}.${value}`] ?? MESSAGES[DEFAULT_LOCALE][`${prefix}.${value}`] ?? value;
}

// useLayoutEffect 在 SSR 上是空操作还会告警，服务端退化为 useEffect。
const useIsomorphicLayoutEffect = typeof window !== 'undefined' ? useLayoutEffect : useEffect;

/**
 * 语言状态 hook。SSR 安全：
 * - 惰性初值用 detectLocale()，但挂载前一律返回 DEFAULT_LOCALE——与服务端快照逐字节一致，
 *   没有 hydration 偏差；
 * - 挂载（layout effect，首帧绘制前）切到本机选择，en 用户看不到中文闪帧；
 * - storage 事件管多标签页，自定义事件管同页面多个实例（LocaleSwitch 与各面板）。
 */
export function useLocale(): [Locale, (locale: Locale) => void] {
  const [locale, setLocaleState] = useState<Locale>(() => detectLocale());
  const [mounted, setMounted] = useState(false);
  useIsomorphicLayoutEffect(() => {
    setMounted(true);
    const sync = (): void => setLocaleState(detectLocale());
    addEventListener('storage', sync);
    addEventListener(LOCALE_EVENT, sync);
    return () => { removeEventListener('storage', sync); removeEventListener(LOCALE_EVENT, sync); };
  }, []);
  useIsomorphicLayoutEffect(() => { if (mounted) applyLocaleToDocument(locale); }, [mounted, locale]);
  const set = useCallback((next: Locale) => setLocale(next), []);
  return [mounted ? locale : DEFAULT_LOCALE, set];
}
